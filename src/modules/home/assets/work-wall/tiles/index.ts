/** A crop window on the 16:9 walkthrough: x, y, width, height as fractions of the frame. */
export type CropRect = readonly [x: number, y: number, w: number, h: number];

/** Crop keyframe: at video time `t` (s) the tile shows `rect`; the tile eases between keys. */
export type CropKey = readonly [t: number, x: number, y: number, w: number, h: number];

export interface WallTile {
  /** The tile still: the first slide's device, cropped (440 px tall WebP). */
  src: StaticImageData;
  /** Tile width / height: 0.8 one phone, 1 two phones, 4/3 three phones or a browser. */
  aspect: number;
  /** Video time of the still; playback starts here so still and motion line up. */
  stillTime: number;
  /** Seconds of the walkthrough the tile loops (the first slides, never the title or outro card). */
  loop: readonly [start: number, end: number];
  /** Where the device is on each slide: the tile pans and zooms to follow it. */
  keys: readonly CropKey[];
}

